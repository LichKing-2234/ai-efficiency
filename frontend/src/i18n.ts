export type MessageKey = keyof typeof messages['en-US']

function browserLocale(): Locale {
  if (typeof localStorage !== 'undefined') {
    const saved = localStorage.getItem(STORAGE_KEY)
    if (saved === 'en-US' || saved === 'zh-CN') {
      return saved
    }
  }
  if (typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('zh')) {
    return 'zh-CN'
  }
  return 'en-US'
}

const locale = ref<Locale>(browserLocale())

function syncDocumentLanguage(next: Locale) {
  if (typeof document !== 'undefined') {
    document.documentElement.lang = next
  }
}

syncDocumentLanguage(locale.value)

export function setLocale(next: Locale) {
  locale.value = next
  if (typeof localStorage !== 'undefined') {
    localStorage.setItem(STORAGE_KEY, next)
  }
  syncDocumentLanguage(next)
}

export function t(key: MessageKey, params?: Record<string, string | number>) {
  let value: string = messages[locale.value][key] || messages['en-US'][key] || key
  if (!params) return value
  for (const [paramKey, paramValue] of Object.entries(params)) {
    value = value.split(`{${paramKey}}`).join(String(paramValue))
  }
  return value
}

export function useI18n() {
  const languageToggleLabel = computed(() => t('nav.languageToggle'))

  function toggleLocale() {
    setLocale(locale.value === 'en-US' ? 'zh-CN' : 'en-US')
  }

  return {
    locale,
    languageToggleLabel,
    setLocale,
    t,
    toggleLocale,
  }
}
